import { spawn } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import readline from "node:readline";
import { StringDecoder } from "node:string_decoder";

const withBot = process.argv.includes("--with-bot");
const dotenvPath = new URL("../.env", import.meta.url);
const apiDevVarsPath = new URL("../apps/api/.dev.vars", import.meta.url);
const services = new Map();
const logs = [];
const maxLogLines = 80;
const pnpmCommand = "pnpm";
let isShuttingDown = false;
let requestedExitCode = 0;
let renderTimer;
let shutdownTimer;

function parseDotEnvValue(rawValue) {
  const value = rawValue.trim();
  const quote = value[0];
  if (
    (quote === '"' || quote === "'") &&
    value.length >= 2 &&
    value[value.length - 1] === quote
  ) {
    const unquoted = value.slice(1, -1);
    if (quote === '"') {
      return unquoted
        .replaceAll("\\n", "\n")
        .replaceAll("\\r", "\r")
        .replaceAll("\\t", "\t")
        .replaceAll('\\"', '"')
        .replaceAll("\\\\", "\\");
    }
    return unquoted;
  }

  const commentIndex = value.search(/\s#/u);
  return (commentIndex === -1 ? value : value.slice(0, commentIndex)).trim();
}

function loadDotEnv(env) {
  let content;
  try {
    content = readFileSync(dotenvPath, "utf8");
  } catch (error) {
    if (
      error &&
      typeof error === "object" &&
      "code" in error &&
      error.code === "ENOENT"
    ) {
      return;
    }
    throw error;
  }

  for (const [index, line] of content.split(/\r?\n/u).entries()) {
    const trimmed = line.trim();
    if (trimmed.length === 0 || trimmed.startsWith("#")) {
      continue;
    }

    const match = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/u.exec(
      trimmed,
    );
    if (!match) {
      appendLog("dev", `Ignoring invalid .env line ${index + 1}`);
      continue;
    }

    const [, key, rawValue] = match;
    if (env[key] === undefined) {
      env[key] = parseDotEnvValue(rawValue);
    }
  }
}

function serializeDotEnvValue(value) {
  if (/^[A-Za-z0-9_./:@-]*$/u.test(value)) {
    return value;
  }
  return `"${value
    .replaceAll("\\", "\\\\")
    .replaceAll("\n", "\\n")
    .replaceAll("\r", "\\r")
    .replaceAll("\t", "\\t")
    .replaceAll('"', '\\"')}"`;
}

function syncApiDevVarsFromEnv(env) {
  const values = new Map([
    [
      "LOCAL_AUTH_BYPASS_SECRET",
      env.LOCAL_AUTH_BYPASS_SECRET ?? "local-auth-bypass-secret",
    ],
  ]);

  for (const key of [
    "CF_ACCESS_CLIENT_ID",
    "CF_ACCESS_CLIENT_SECRET",
    "CF_ACCESS_TEAM_DOMAIN",
    "CF_ACCESS_AUD",
    "NVIDIA_NIM_BASE_URL",
  ]) {
    if (env[key]) {
      values.set(key, env[key]);
    }
  }

  if (env.LLM_PROVIDER === "fake" || env.LLM_PROVIDER === "nvidia_nim") {
    values.set("LLM_PROVIDER", env.LLM_PROVIDER);
  }
  if (env.NVIDIA_NIM_BEARER_TOKEN) {
    values.set("NVIDIA_NIM_BEARER_TOKEN", env.NVIDIA_NIM_BEARER_TOKEN);
  }

  let lines;
  try {
    lines = readFileSync(apiDevVarsPath, "utf8").split(/\r?\n/u);
  } catch (error) {
    if (
      !error ||
      typeof error !== "object" ||
      !("code" in error) ||
      error.code !== "ENOENT"
    ) {
      throw error;
    }
    lines = [
      "# Generated by scripts/dev.mjs for local `wrangler dev`.",
      "# Do not commit this file.",
    ];
  }

  const seenKeys = new Set();
  const updatedLines = lines.map((line) => {
    const match = /^([A-Za-z_][A-Za-z0-9_]*)\s*=.*$/u.exec(line);
    if (!match || !values.has(match[1])) {
      return line;
    }
    const key = match[1];
    seenKeys.add(key);
    return `${key}=${serializeDotEnvValue(values.get(key))}`;
  });

  for (const [key, value] of values) {
    if (!seenKeys.has(key)) {
      updatedLines.push(`${key}=${serializeDotEnvValue(value)}`);
    }
  }

  writeFileSync(apiDevVarsPath, `${updatedLines.join("\n").trimEnd()}\n`);
}

function appendLog(serviceName, line) {
  const timestamp = new Date().toLocaleTimeString("en-GB", { hour12: false });
  const formattedLine = `[${timestamp}] ${serviceName.padEnd(7)} ${line}`;
  logs.push(formattedLine);
  while (logs.length > maxLogLines) {
    logs.shift();
  }
  if (!process.stdout.isTTY) {
    process.stdout.write(`${formattedLine}\n`);
  }
  render();
}

function attachLogStream(serviceName, stream) {
  const decoder = new StringDecoder("utf8");
  let pending = "";
  stream.on("data", (chunk) => {
    pending += decoder.write(chunk);
    const lines = pending.split(/\r?\n/u);
    pending = lines.pop() ?? "";
    for (const line of lines) {
      if (line.length > 0) {
        appendLog(serviceName, line);
      }
    }
  });
  stream.on("end", () => {
    pending += decoder.end();
    if (pending.length > 0) {
      appendLog(serviceName, pending);
    }
  });
}

function quoteWindowsCommandPart(value) {
  if (/^[A-Za-z0-9_./:@=-]+$/u.test(value)) {
    return value;
  }
  return `"${value.replaceAll('"', '""')}"`;
}

function serviceRows() {
  return [...services.values()].map((service) => {
    const pid = service.child?.pid ? String(service.child.pid) : "-";
    const status = service.status.padEnd(10);
    return `${service.name.padEnd(7)} ${status} pid ${pid}`;
  });
}

function render() {
  if (!process.stdout.isTTY) {
    return;
  }

  const height = process.stdout.rows ?? 30;
  const width = process.stdout.columns ?? 100;
  const headerLines = [
    "dc-chatbot dev",
    "q: stop all  Ctrl+C: stop all",
    "",
    "Services",
    ...serviceRows(),
    "",
    "Logs",
  ];
  const logLimit = Math.max(1, height - headerLines.length - 1);
  const visibleLogs = logs.slice(-logLimit).map((line) => fitLine(line, width));

  readline.cursorTo(process.stdout, 0, 0);
  readline.clearScreenDown(process.stdout);
  process.stdout.write([...headerLines, ...visibleLogs].join("\n"));
}

function fitLine(value, width) {
  if (value.length <= width) {
    return value;
  }
  return value.slice(0, Math.max(0, width - 1));
}

function configureTui() {
  if (!process.stdin.isTTY || !process.stdout.isTTY) {
    process.stdin.setEncoding("utf8");
    process.stdin.on("data", (chunk) => {
      if (String(chunk).includes("q")) {
        shutdown(0);
      }
    });
    return;
  }

  process.stdin.setEncoding("utf8");
  readline.emitKeypressEvents(process.stdin);
  process.stdin.setRawMode(true);
  process.stdin.resume();
  process.stdin.on("keypress", (_text, key) => {
    if (key.ctrl && key.name === "c") {
      shutdown(0);
      return;
    }
    if (key.name === "q") {
      shutdown(0);
    }
  });
  renderTimer = setInterval(render, 1_000);
  renderTimer.unref();
  render();
}

function restoreTerminal() {
  if (renderTimer) {
    clearInterval(renderTimer);
  }
  if (process.stdin.isTTY) {
    process.stdin.setRawMode(false);
  }
  if (process.stdout.isTTY) {
    readline.cursorTo(process.stdout, 0, 0);
    readline.clearScreenDown(process.stdout);
  }
}

function runPnpm(args, name, options = {}) {
  const child = spawn(
    process.platform === "win32"
      ? [pnpmCommand, ...args].map(quoteWindowsCommandPart).join(" ")
      : pnpmCommand,
    process.platform === "win32" ? [] : args,
    {
      detached: process.platform !== "win32",
      env: process.env,
      shell: process.platform === "win32",
      stdio: ["ignore", "pipe", "pipe"],
      windowsHide: true,
    },
  );

  const service = {
    child,
    name,
    status: "starting",
    treeKilled: false,
  };
  services.set(name, service);

  attachLogStream(name, child.stdout);
  attachLogStream(name, child.stderr);

  child.once("spawn", () => {
    service.status = options.prepare ? "running" : "ready";
    render();
  });
  child.once("exit", (code, signal) => {
    service.status =
      code === 0 || isShuttingDown
        ? "stopped"
        : signal
          ? `signal:${signal}`
          : `exit:${code ?? "?"}`;
    render();

    if (options.prepare) {
      services.delete(name);
      render();
      return;
    }

    if (!isShuttingDown) {
      appendLog(
        "dev",
        `${name} stopped unexpectedly${
          signal
            ? ` with signal ${signal}`
            : ` with exit code ${code ?? "unknown"}`
        }`,
      );
      shutdown(code && code > 0 ? code : 1);
    }
  });
  child.once("error", (error) => {
    service.status = "failed";
    appendLog(name, `failed to start: ${error.message}`);
    if (!isShuttingDown) {
      shutdown(1);
    }
  });

  return { child, service };
}

function runPnpmToCompletion(args, name) {
  return new Promise((resolve, reject) => {
    const { child } = runPnpm(args, name, { prepare: true });
    child.once("exit", (code, signal) => {
      if (code === 0) {
        resolve();
        return;
      }
      reject(
        new Error(
          `pnpm ${args.join(" ")} failed${
            signal
              ? ` with signal ${signal}`
              : ` with exit code ${code ?? "unknown"}`
          }`,
        ),
      );
    });
    child.once("error", reject);
  });
}

function startService(name, args) {
  runPnpm(args, name);
}

async function waitForApi() {
  const url = "http://127.0.0.1:8787/health";
  const service = {
    child: null,
    name: "Bot",
    status: "waiting",
    treeKilled: true,
  };
  services.set("Bot", service);
  render();

  for (let attempt = 1; attempt <= 60; attempt += 1) {
    if (isShuttingDown) {
      throw new Error("Startup stopped");
    }
    try {
      const response = await fetch(url);
      if (response.ok) {
        appendLog("dev", "API is healthy; starting Bot Worker");
        services.delete("Bot");
        render();
        return;
      }
    } catch {
      // API is still starting.
    }
    await new Promise((resolve) => setTimeout(resolve, 1_000));
  }
  throw new Error(`API did not become healthy: ${url}`);
}

function killServiceTree(service, force) {
  const child = service.child;
  if (!child?.pid || child.exitCode !== null || service.treeKilled) {
    return;
  }

  if (process.platform === "win32") {
    if (!force) {
      return;
    }
    service.treeKilled = true;
    spawn("taskkill", ["/pid", String(child.pid), "/t", "/f"], {
      stdio: "ignore",
      windowsHide: true,
    });
    return;
  }

  try {
    process.kill(-child.pid, force ? "SIGKILL" : "SIGTERM");
  } catch {
    try {
      child.kill(force ? "SIGKILL" : "SIGTERM");
    } catch {
      // The process already exited.
    }
  }
}

function shutdown(exitCode = 0) {
  if (isShuttingDown) {
    return;
  }
  isShuttingDown = true;
  requestedExitCode = exitCode;
  appendLog("dev", "Stopping services...");

  for (const service of services.values()) {
    service.status = service.child ? "stopping" : "stopped";
    killServiceTree(service, false);
  }
  render();

  shutdownTimer = setTimeout(() => {
    for (const service of services.values()) {
      killServiceTree(service, true);
    }
    finishWhenStopped();
  }, process.platform === "win32" ? 0 : 5_000);
  shutdownTimer.unref();
  finishWhenStopped();
}

function finishWhenStopped() {
  const runningServices = [...services.values()].filter(
    (service) =>
      service.child &&
      service.child.exitCode === null &&
      service.child.signalCode === null,
  );
  if (runningServices.length > 0) {
    setTimeout(finishWhenStopped, 100).unref();
    return;
  }

  if (shutdownTimer) {
    clearTimeout(shutdownTimer);
  }
  restoreTerminal();
  process.exit(requestedExitCode);
}

process.once("SIGINT", () => shutdown(0));
process.once("SIGTERM", () => shutdown(0));

configureTui();

try {
  loadDotEnv(process.env);
  syncApiDevVarsFromEnv(process.env);
  await runPnpmToCompletion(
    ["--filter", "@dc-chatbot/api", "dev:prepare"],
    "Prepare",
  );
  startService("API", ["--filter", "@dc-chatbot/api", "dev"]);
  startService("Web", ["--filter", "@dc-chatbot/web", "dev"]);

  if (withBot) {
    await waitForApi();
    startService("Bot", ["--filter", "@dc-chatbot/bot", "dev"]);
  }
} catch (error) {
  appendLog("dev", error instanceof Error ? error.message : String(error));
  shutdown(1);
}
